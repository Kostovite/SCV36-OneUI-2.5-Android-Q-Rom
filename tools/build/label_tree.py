#!/usr/bin/env python3
"""Set security.selinux xattrs on a mounted tree from Android file_contexts files (like the build's e2fsdroid would).
usage: sudo python3 label_tree.py <mount_root> <path_prefix_in_image> <runtime_prefix> <file_contexts>...
e.g.   sudo python3 label_tree.py /mnt/sys /system/vendor /vendor plat_file_contexts vendor_file_contexts
Files under <path_prefix_in_image> are labelled as if they lived at <runtime_prefix> (the S8 keeps its vendor in
/system/vendor but it must carry the labels of a real /vendor partition, otherwise "/system(/.*)?" -> system_file wins).
Spec precedence follows AOSP fc_sort: exact paths beat regexes; among regexes the longer fixed stem wins, then the
longer spec string, then a spec with a file type, then the later spec."""
import os, re, sys

args = sys.argv[1:]
emit = None
if args[0] == '--emit-sh':          # write a chcon script instead of setting xattrs (for applying in TWRP)
    emit = open(args[1], 'w', newline='\n'); args = args[2:]
    emit.write('#!/sbin/sh\n# generated by label_tree.py: SELinux labels for the S8 port vendor\n'
               'V=${1:-/system_root/system/vendor}\n')
root, prefix, runtime, *fcs = args
TYPES = {'--': 'f', '-d': 'd', '-l': 'l', '-s': 's', '-p': 'p', '-b': 'b', '-c': 'c'}
META = re.compile(r'[.*+?^$|()\[\]{}\\]')
specs = []
order = 0
for fc in fcs:
    for line in open(fc):
        p = line.split()
        if len(p) < 2 or not p[0].startswith('/'):
            continue
        rx, ftype, ctx = p[0], (TYPES.get(p[1]) if len(p) == 3 else None), p[-1]
        m = META.search(rx)
        exact = m is None
        stem = len(rx) if exact else m.start()
        order += 1
        try:
            specs.append((re.compile('^' + rx + '$'), ftype, ctx, (exact, stem, len(rx), ftype is not None, order)))
        except re.error:
            pass


def kind(path):
    if os.path.islink(path): return 'l'
    if os.path.isdir(path): return 'd'
    return 'f'


def label(rt_path, k):
    best = None
    for rx, ft, ctx, rank in specs:
        if (ft is None or ft == k) and rx.match(rt_path) and (best is None or rank > best[1]):
            best = (ctx, rank)
    return best[0] if best else None


count, unlabeled, stats = 0, [], {}
base = os.path.join(root, prefix.lstrip('/'))
for dp, dirs, files in os.walk(base):
    for name in [''] + dirs + files:
        full = os.path.join(dp, name) if name else dp
        img = '/' + os.path.relpath(full, root).replace(os.sep, '/')
        rt = runtime + img[len(prefix):]
        ctx = label(rt, kind(full))
        if not ctx:
            unlabeled.append(rt); continue
        if emit:
            rel = img[len(prefix):]
            emit.write(f'chcon -h {ctx} "$V{rel}"\n')
        else:
            os.setxattr(full, 'security.selinux', ctx.encode() + b'\0', follow_symlinks=False)
        stats[ctx] = stats.get(ctx, 0) + 1
        count += 1
print(f'labelled {count} entries under {prefix} (as {runtime}); unlabeled {len(unlabeled)}', unlabeled[:5])
for ctx, n in sorted(stats.items(), key=lambda x: -x[1])[:8]:
    print(f'   {n:6}  {ctx}')
